import { buildSnapshot } from '../docs/slide-skills/risk-snapshot/scripts/model.mjs';
const num = value => typeof value === 'number' && Number.isFinite(value);
export function matchRiskHoldings(input, holdings) {
  if (!Array.isArray(input) || input.length !== holdings.length) throw Error('Risk inputs must cover every holding in the uploaded portfolio.');
  const map = new Map(holdings.map(holding => [holding.ticker.toUpperCase(), holding.value]));
  const seen = new Set();
  for (const holding of input) {
    const ticker = holding.ticker?.trim().toUpperCase();
    if (!ticker || seen.has(ticker) || !map.has(ticker) || !num(holding.value) || Math.abs(map.get(ticker)-holding.value) > .01) throw Error('Risk input tickers and position values must match the confirmed portfolio. Download a new template for this portfolio.');
    seen.add(ticker);
  }
}
export function createRiskSnapshot(input, holdings) {
  input = input?.model_input || input;
  if (!input || typeof input !== 'object') throw Error('Upload the risk input template or a snapshot generated by the repository skill.');
  matchRiskHoldings(input.holdings, holdings);
  if (input.correlation) throw Error('Custom correlation matrices are not supported in the app. Use aligned history or the skill’s documented class assumptions.');
  const snapshot = buildSnapshot(input);
  const values = [snapshot.risk_score, snapshot.range.downside_pct, snapshot.range.upside_pct, snapshot.metrics.annual_volatility_pct];
  if (!values.every(num) || snapshot.range.downside_pct < -100) throw Error('These inputs produce an invalid modeled range. Review the history frequency and return assumptions.');
  return snapshot;
}
export function riskInputTemplate(holdings, positions, asOf, client) {
  return {as_of:asOf,portfolio_label:'Current portfolio',client_label:client,periods_per_year:null,risk_free_pct:null,advisory_fee_pct:null,history_dates:[],holdings:holdings.map(holding => {
    const matches=positions.filter(position=>position.ticker===holding.ticker), classes=new Set(matches.map(position=>position.assetClass?.toLowerCase()));
    const source=classes.size===1?[...classes][0]:'';
    const asset_class = /^(stock|stocks|equity|equities)$/.test(source)?'stocks':/^(bond|bonds|fixed income)$/.test(source)?'bonds':source==='cash'?'cash':source==='other'?'other':'';
    return {...holding,asset_class,annual_return_pct:null,annual_vol_pct:null,yield_pct:null,expense_ratio_pct:null,tax_drag_pct:null,max_drawdown_pct:null};
  })};
}
